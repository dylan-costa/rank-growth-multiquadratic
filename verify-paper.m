end procedure;

// Square-free part of a nonzero rational number.
function Sqf(q)
    n := Numerator(q) * Denominator(q);
    s := Sign(n);
    for pe in Factorization(Abs(n)) do
        if IsOdd(pe[2]) then s *:= pe[1]; end if;
    end for;
    return s;
end function;

// The square classes generated by gens: all Sqf of products of subsets.
function SquareClasses(gens)
    S := {1};
    for g in gens do
        S join:= {Sqf(s * g) : s in S};
    end for;
    return S;
end function;

// Proven rank of E^d (d = 1 means E itself), or -1 if RankBounds cannot decide.
function TwistRank(E, d)
    Ed := d eq 1 select E else QuadraticTwist(E, d);
    lo, hi := RankBounds(Ed);
    return lo eq hi select lo else -1;
end function;

// A curve whose a-invariants agree with those of E modulo p^k.
function ModelModP(E, p, k)
    return EllipticCurve([(Integers()!a) mod p^k : a in aInvariants(E)]);
end function;

// Local root number of E at p, for p a bad prime.
// Large primes: the reduction is multiplicative (checked) and the model is
// minimal there (c4 is a unit); W_p = -1 if the reduction is split, i.e. if
// -c6 is a square mod p, and +1 otherwise (Proposition 4.1).
// Small primes: RootNumber(E, p), on a curve that agrees with E modulo p^40
// (same curve over Q_p up to isomorphism, so same local root number; this
// avoids a slow path of Magma 2.25 at additive primes of huge curves).
function LocalW(E, p)
    if p gt 10^6 then
        c4 := Integers()!cInvariants(E)[1];
        c6 := Integers()!cInvariants(E)[2];
        error if c4 mod p eq 0, "LocalW: reduction at large prime not multiplicative", p;
        return -KroneckerSymbol(-c6, p);
    end if;
    return RootNumber(ModelModP(E, p, 40), p);
end function;

// The same, but on the reduced model also checking agreement with p^30.
function LocalWStable(E, p)
    w := LocalW(E, p);
    if p le 10^6 then
        error if RootNumber(ModelModP(E, p, 30), p) ne w, "LocalWStable: unstable at", p;
    end if;
    return w;
end function;


